"""Generates crates/ml-convertant-ggml/src/iq3s_grid.rs from a llama.cpp checkout.
usage: gen_iq3s_grid.py <llama.cpp dir> <out.rs>
Reads `iq3s_grid` (ggml/src/ggml-common.h) and `kgrid_512` (ggml/src/ggml-quants.c, `iq3xs_init_impl`), checks that
the two describe the same 512 points (byte k of an `iq3s_grid` entry is 2 * ((kgrid_512 >> 3k) & 7) + 1, which is how
ggml builds its encoder grid from kgrid_512), and writes the table as Rust.  CI re-runs this against the pinned
checkout and diffs the result against the committed file, so our copy is verified against its origin, not just copied."""
import re, sys
root, out = sys.argv[1], sys.argv[2]
common = open(root + '/ggml/src/ggml-common.h', encoding='utf-8').read()
quants = open(root + '/ggml/src/ggml-quants.c', encoding='utf-8').read()
m = re.search(r'GGML_TABLE_BEGIN\(uint32_t, iq3s_grid, 512\)(.*?)GGML_TABLE_END\(\)', common, re.S)
grid = [int(v, 16) for v in re.findall(r'0x[0-9a-fA-F]+', m.group(1))]
m = re.search(r'static const uint16_t kgrid_512\[512\] = \{(.*?)\};', quants, re.S)
kgrid = [int(v) for v in re.findall(r'\d+', m.group(1))]
assert len(grid) == 512 and len(kgrid) == 512, (len(grid), len(kgrid))
for i, (g, k) in enumerate(zip(grid, kgrid)):
    want = sum((2 * ((k >> (3 * j)) & 7) + 1) << (8 * j) for j in range(4))
    assert g == want, (i, hex(g), hex(want))
lines = ['// @generated by tools/golden/gen_iq3s_grid.py from llama.cpp ggml/src/ggml-common.h `iq3s_grid`; do not edit.',
         '// Origin: https://github.com/ggml-org/llama.cpp commit 9d57ce456c94d241dde672b2db9cf18879766568, MIT, Copyright (c) 2023-2026 The ggml authors',
         '// (see THIRD-PARTY-NOTICES.md and tools/golden/LICENSE-ggml-MIT). Each entry holds four little-endian bytes 2 * l + 1, l in 0..8.',
         '',
         'pub(crate) const IQ3S_GRID: [u32; 512] = [']
for i in range(0, 512, 8):
    lines.append('    ' + ', '.join('0x%08x' % v for v in grid[i:i + 8]) + ',')
lines.append('];')
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('ok', len(grid))
