"""Generates crates/ml-convertant-ggml/src/iq_tables.rs from a llama.cpp checkout.
usage: gen_iq_tables.py <llama.cpp dir> <out.rs>
Extracts the lookup tables the IQ decoders use from ggml/src/ggml-common.h: `kmask_iq2xs`, `ksigns_iq2xs`, `iq3xxs_grid`, `iq2xxs_grid`, `iq2xs_grid`.
Each is written as Rust data with its length checked against the declaration.  CI re-runs this against the pinned
checkout and diffs the result against the committed file, so our copy is verified against its origin, not just copied."""
import re, sys
root, out = sys.argv[1], sys.argv[2]
common = open(root + '/ggml/src/ggml-common.h', encoding='utf-8').read()
# (C name, C element type, Rust name, Rust element type, hex width, per line)
TABLES = [
    ('kmask_iq2xs', 'uint8_t', 'KMASK_IQ2XS', 'u8', 2, 8),
    ('ksigns_iq2xs', 'uint8_t', 'KSIGNS_IQ2XS', 'u8', 2, 16),
    ('iq3xxs_grid', 'uint32_t', 'IQ3XXS_GRID', 'u32', 8, 8),
    ('iq2xxs_grid', 'uint64_t', 'IQ2XXS_GRID', 'u64', 16, 4),
    ('iq2xs_grid', 'uint64_t', 'IQ2XS_GRID', 'u64', 16, 4),
]
lines = ['// @generated by tools/golden/gen_iq_tables.py from llama.cpp ggml/src/ggml-common.h; do not edit.',
         '// Origin: https://github.com/ggml-org/llama.cpp commit 9d57ce456c94d241dde672b2db9cf18879766568, MIT, Copyright (c) 2023-2026 The ggml authors',
         '// (see THIRD-PARTY-NOTICES.md and tools/golden/LICENSE-ggml-MIT). A u32/u64 grid entry holds four/eight little-endian bytes.',
         '']
for cname, cty, rname, rty, width, per in TABLES:
    m = re.search(r'GGML_TABLE_BEGIN\(%s, %s, (\d+)\)(.*?)GGML_TABLE_END\(\)' % (cty, cname), common, re.S)
    n = int(m.group(1))
    vals = [int(v, 0) for v in re.findall(r'0x[0-9a-fA-F]+|\d+', m.group(2))]
    assert len(vals) == n, (cname, len(vals), n)
    lines.append('pub(crate) const %s: [%s; %d] = [' % (rname, rty, n))
    for i in range(0, n, per):
        lines.append('    ' + ', '.join(('0x%0' + str(width) + 'x') % v for v in vals[i:i + per]) + ',')
    lines.append('];')
    lines.append('')
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines).rstrip('\n') + '\n')
print('ok', len(TABLES))
